--- Sessions are now called activities: tables, columns and indexes follow the new name

ALTER TABLE SESSION RENAME TO ACTIVITY;
ALTER TABLE SESSION_DATA RENAME TO ACTIVITY_DATA;
ALTER TABLE SESSION_LAP RENAME TO ACTIVITY_LAP;
ALTER TABLE SESSION_STEP RENAME TO ACTIVITY_STEP;

ALTER TABLE ACTIVITY_DATA RENAME COLUMN session TO activity;
ALTER TABLE ACTIVITY_LAP RENAME COLUMN session TO activity;
ALTER TABLE ACTIVITY_STEP RENAME COLUMN session TO activity;
ALTER TABLE WORKOUT_PLANNING RENAME COLUMN session TO activity;

-- Indexes keep their names through a table rename, so they are recreated
DROP INDEX SESSION_NAME;
CREATE INDEX ACTIVITY_NAME ON ACTIVITY(name);
DROP INDEX SESSION_WORKOUT;
CREATE INDEX ACTIVITY_WORKOUT ON ACTIVITY(workout);
DROP INDEX SESSION_STEP_SESSION_PR;
CREATE INDEX ACTIVITY_STEP_ACTIVITY_PR ON ACTIVITY_STEP(activity, pr);
DROP INDEX SESSION_STEP_EXERCISE_PR;
CREATE UNIQUE INDEX ACTIVITY_STEP_EXERCISE_PR ON ACTIVITY_STEP(exercise_category, exercise_id) WHERE pr = true;
DROP INDEX SESSION_STEP_EXERCISE_RECORD;
CREATE INDEX ACTIVITY_STEP_EXERCISE_RECORD ON ACTIVITY_STEP(exercise_category, exercise_id, weight DESC, reps DESC, activity, idx);
DROP INDEX WORKOUT_PLANNING_SESSION;
CREATE INDEX WORKOUT_PLANNING_ACTIVITY ON WORKOUT_PLANNING(activity);
